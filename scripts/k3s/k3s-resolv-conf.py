#!/usr/bin/env python3
"""Keep kubelet's upstream resolver list within its three-server limit."""
import ipaddress
import os
from pathlib import Path
import sys
import tempfile


def bounded_resolv_conf(source):
    servers = []
    directives = []
    for line in source.splitlines():
        fields = line.split('#', 1)[0].split()
        if not fields:
            continue
        if fields[0] == 'nameserver' and len(fields) == 2:
            try:
                address = ipaddress.ip_address(fields[1])
            except ValueError:
                continue
            if (address.is_loopback or address.is_link_local
                    or address.is_unspecified or address.is_multicast):
                continue
            server = str(address)
            if server not in servers and len(servers) < 3:
                servers.append(server)
        elif fields[0] in ('search', 'domain', 'options'):
            directives.append(' '.join(fields))
    if not servers:
        raise ValueError('No usable upstream nameservers; keeping previous resolver file')
    return ('# Generated by k3s-resolv-conf.py; edit the host DNS configuration.\n'
            + ''.join('nameserver ' + server + '\n' for server in servers)
            + ''.join(line + '\n' for line in directives))


def refresh(source, target):
    content = bounded_resolv_conf(source.read_text())
    if target.exists() and target.read_text() == content:
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    name = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', dir=target.parent, delete=False) as f:
            name = f.name
            f.write(content)
            f.flush()
            os.fchmod(f.fileno(), 0o644)
        os.replace(name, target)
    finally:
        if name and os.path.exists(name):
            os.unlink(name)


if __name__ == '__main__':
    source = Path(sys.argv[1] if len(sys.argv) > 1 else '/run/systemd/resolve/resolv.conf')
    target = Path(sys.argv[2] if len(sys.argv) > 2 else '/etc/rancher/k3s/resolv.conf')
    refresh(source, target)
