#!/usr/bin/env python3
"""Install a separate, atomic nftables input guard; never flush other tables."""
import argparse
import ipaddress
import json
from pathlib import Path
import shlex
import subprocess

TABLE = 'selfhosted_host_guard'
SERVICE = '''[Unit]
Description=Selfhosted infrastructure listener containment
Before=k3s.service k3s-agent.service
After=local-fs.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f /etc/selfhosted/host-guard.nft
ExecReload=/usr/sbin/nft -f /etc/selfhosted/host-guard.nft

[Install]
WantedBy=multi-user.target
'''
DEPENDENCY = '''[Unit]
Requires=selfhosted-host-guard.service
After=selfhosted-host-guard.service
'''

def render(node, nodes):
    addresses = [ipaddress.ip_address(a['address']) for n in nodes
                 for a in n['status']['addresses'] if a['type'] == 'InternalIP']
    peers = sorted(str(a) for a in addresses if a.version == 4)
    peers6 = sorted(str(a) for a in addresses if a.version == 6)
    control_addresses = [ipaddress.ip_address(a['address']) for n in nodes
                         if 'node-role.kubernetes.io/control-plane' in n['metadata']['labels']
                         for a in n['status']['addresses'] if a['type'] == 'InternalIP']
    control4 = sorted(str(a) for a in control_addresses if a.version == 4)
    control6 = sorted(str(a) for a in control_addresses if a.version == 6)
    assert control4, 'No control-plane addresses found'
    cidr = str(ipaddress.IPv4Network(node['spec']['podCIDR']))
    return f'''# Generated by infra/host-containment/apply.py; this table only.
add table inet {TABLE}
flush table inet {TABLE}
table inet {TABLE} {{
  set nodes {{ type ipv4_addr; elements = {{ {', '.join(peers)} }}; }}
  set nodes6 {{ type ipv6_addr; elements = {{ {", ".join(peers6)} }}; }}
  set control4 {{ type ipv4_addr; elements = {{ {', '.join(control4)} }}; }}
  set control6 {{ type ipv6_addr; elements = {{ {', '.join(control6)} }}; }}
  chain input {{
    type filter hook input priority -10; policy accept;
    iifname "lo" accept
    # Development listeners found on the primary node are local-only.
    tcp dport {{ 3777, 8899, 8900 }} counter drop
    # Administrative APIs: retain LAN IPv4, tailnet and cluster callers.
    ip saddr 192.168.4.0/24 tcp dport {{ 22, 6443 }} counter accept
    iifname "tailscale0" tcp dport {{ 22, 6443 }} counter accept
    ip6 saddr @nodes6 tcp dport {{ 22, 6443 }} counter accept
    iifname {{ "cni0", "flannel.1" }} ip saddr 10.42.0.0/16 tcp dport 6443 counter accept
    tcp dport {{ 22, 6443 }} counter drop
    # Etcd peer/client ports are only for the three control-plane hosts.
    ip saddr @control4 tcp dport {{ 2379, 2380 }} counter accept
    ip6 saddr @control6 tcp dport {{ 2379, 2380 }} counter accept
    tcp dport {{ 2379, 2380 }} counter drop
    # Only this node's pod network needs to scrape its exporter. Pod egress
    # NetworkPolicies further constrain callers. No LAN/tailnet metrics access.
    iifname "cni0" ip saddr {cidr} tcp dport 9100 counter accept
    tcp dport {{ 9100, 29642, 29643, 29644 }} counter drop
    # VXLAN is an unauthenticated overlay; accept only cluster node sources.
    ip saddr @nodes udp dport 8472 counter accept
    ip6 saddr @nodes6 udp dport 8472 counter accept
    udp dport 8472 counter drop
    # Authenticated kubelet APIs are for control-plane and pod monitoring.
    ip saddr @nodes tcp dport 10250 counter accept
    iifname {{ "cni0", "flannel.1" }} ip saddr 10.42.0.0/16 tcp dport 10250 counter accept
    ip6 saddr @nodes6 tcp dport 10250 counter accept
    tcp dport 10250 counter drop
    # RPC binding is infrastructure-only, not a LAN or tailnet service.
    ip saddr @nodes meta l4proto {{ tcp, udp }} th dport 111 counter accept
    ip6 saddr @nodes6 meta l4proto {{ tcp, udp }} th dport 111 counter accept
    ip saddr 192.168.4.36 meta l4proto {{ tcp, udp }} th dport 111 counter accept
    meta l4proto {{ tcp, udp }} th dport 111 counter drop
  }}
}}
'''

def install(rules):
    # Validate and apply the entire table in a single nft transaction. A failed
    # update leaves the current rules intact. Do not restart k3s or tailscaled.
    files = {'/etc/selfhosted/host-guard.nft': rules,
             '/etc/systemd/system/selfhosted-host-guard.service': SERVICE,
             '/etc/systemd/system/k3s.service.d/40-host-guard.conf': DEPENDENCY,
             '/etc/systemd/system/k3s-agent.service.d/40-host-guard.conf': DEPENDENCY}
    script = 'set -eu\nk3s_before=$(systemctl show k3s k3s-agent -p MainPID)\ncommand -v nft >/dev/null\ntmp=$(mktemp)\ntrap \'rm -f "$tmp"\' EXIT\n'
    script += "cat > \"$tmp\" <<'HOST_GUARD_RULES'\n" + rules + 'HOST_GUARD_RULES\n'
    script += 'nft --check -f "$tmp"\nnft -f "$tmp"\n'
    for path, content in files.items():
        script += f'install -d -m 755 {shlex.quote(str(Path(path).parent))}\n'
        script += f"cat > {shlex.quote(path + '.new')} <<'HOST_GUARD_FILE'\n{content}HOST_GUARD_FILE\n"
        script += f'chmod 644 {shlex.quote(path + ".new")}\nmv -f {shlex.quote(path + ".new")} {shlex.quote(path)}\n'
    script += 'systemctl daemon-reload\nsystemctl enable selfhosted-host-guard.service\nsystemctl start selfhosted-host-guard.service\nsystemctl is-active selfhosted-host-guard.service\ntest "$k3s_before" = "$(systemctl show k3s k3s-agent -p MainPID)"\necho K3S_PIDS_PRESERVED\n'
    return script

def via_kubernetes(node, script):
    # Explicit break-glass bootstrap for a node whose tailnet key expired.
    # No persistent agent or service-account token; remove the Job in finally.
    import uuid
    name = 'host-guard-install-' + uuid.uuid4().hex[:8]
    job = {'apiVersion': 'batch/v1', 'kind': 'Job',
           'metadata': {'name': name, 'namespace': 'kube-system'},
           'spec': {'backoffLimit': 0, 'activeDeadlineSeconds': 120,
                    'template': {'spec': {
                        'nodeName': node, 'hostNetwork': True, 'hostPID': True,
                        'automountServiceAccountToken': False, 'restartPolicy': 'Never',
                        'containers': [{'name': 'install', 'image': 'busybox:1.37.0',
                            'command': ['nsenter', '-t', '1', '-m', '-u', '-i', '-n', '-p', '--', '/bin/bash', '-c', script],
                            'securityContext': {'runAsUser': 0, 'privileged': True},
                            'resources': {'requests': {'cpu': '10m', 'memory': '32Mi'}, 'limits': {'memory': '128Mi'}}}]}}}}
    try:
        subprocess.run(['kubectl', 'apply', '-f', '-'], input=json.dumps(job), text=True, check=True)
        result = subprocess.run(['kubectl', '-n', 'kube-system', 'wait', '--for=condition=Complete',
                                 'job/'+name, '--timeout=130s'])
        subprocess.run(['kubectl', '-n', 'kube-system', 'logs', 'job/'+name], check=True)
        result.check_returncode()
    finally:
        subprocess.run(['kubectl', '-n', 'kube-system', 'delete', 'job', name, '--ignore-not-found'], check=True)

if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--via-kubernetes', action='store_true', help='Explicit temporary admin Job instead of tailnet SSH')
    ap.add_argument('--node', help='Canary node; omit to process the fleet sequentially')
    args = ap.parse_args()
    if args.via_kubernetes and not args.node:
        ap.error('--via-kubernetes requires an explicit --node')
    nodes = json.loads(subprocess.check_output(['kubectl', 'get', 'nodes', '-o', 'json']))['items']
    selected = [n for n in nodes if not args.node or n['metadata']['name'] == args.node]
    if not selected:
        ap.error('Node not found')
    for node in selected:
        name = node['metadata']['name']
        rules = render(node, nodes)
        if args.apply:
            if args.via_kubernetes:
                via_kubernetes(name, install(rules))
            else:
                subprocess.run(['tailscale', 'ssh', 'root@'+name, 'bash -s'],
                               input=install(rules), text=True, check=True, timeout=60)
            print(name, 'guard active', flush=True)
        else:
            print('#', name, '\n', rules)
